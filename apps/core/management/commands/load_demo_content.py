class Command(BaseCommand):
    help = "بارگذاری محتوای اولیه سایت (خودروها با مشخصات، خدمات، گارانتی، تنظیمات و پاسخ‌های چت‌بات)"

    def handle(self, *args, **options):
        self.site_settings()
        self.cars()
        self.services()
        self.warranty()
        self.bot()
        self.stdout.write(self.style.SUCCESS("\nپایان. همه موارد از پنل مدیریت قابل ویرایش هستند."))

    def ok(self, msg):
        self.stdout.write(self.style.SUCCESS(f"✓ {msg}"))

    def skip(self, msg):
        self.stdout.write(f"• {msg}")

    def attach(self, field, rel_path):
        path = STATIC_IMG / rel_path
        with open(path, "rb") as f:
            field.save(path.name, File(f), save=False)

    def site_settings(self):
        site = SiteSettings.load()
        changed = [k for k, v in SITE_DEFAULTS.items() if not getattr(site, k)]
        for k in changed:
            setattr(site, k, SITE_DEFAULTS[k])
        if changed:
            site.save()
            self.ok(f"تنظیمات سایت تکمیل شد ({len(changed)} فیلد خالی)")
        else:
            self.skip("تنظیمات سایت از قبل کامل بود")

    def cars(self):
        for order, data in enumerate(CARS):
            if Car.objects.filter(title=data["title"]).exists():
                self.skip(f"خودروی «{data['title']}» از قبل وجود دارد")
                continue
            category, _ = CarCategory.objects.get_or_create(title=data["category"])
            car = Car(
                title=data["title"], category=category, tagline=data["tagline"], summary=data["summary"],
                description=data["description"] + SPEC_NOTE, price_text="طبق آخرین بخشنامه فروش سایپا",
                is_featured=data["featured"], order=order,
            )
            self.attach(car.image, data["image"])
            car.save()
            for i, (group, title, value) in enumerate(data["specs"]):
                CarSpec.objects.create(car=car, group=group, title=title, value=value, order=i)
            for i, (path, caption) in enumerate(data["gallery"]):
                img = CarImage(car=car, caption=caption, order=i)
                self.attach(img.image, path)
                img.save()
            for name, hex_code in data["colors"]:
                CarColor.objects.create(car=car, name=name, hex_code=hex_code)
            self.ok(f"خودروی «{car.title}» با {len(data['specs'])} مشخصه فنی")

    def services(self):
        for order, (title, icon, summary) in enumerate(SERVICES):
            _, created = Service.objects.get_or_create(title=title, defaults={"icon": icon, "summary": summary, "order": order})
            (self.ok if created else self.skip)(f"خدمت «{title}»" + ("" if created else " از قبل وجود دارد"))

    def warranty(self):
        for order, data in enumerate(PLANS):
            plan, created = WarrantyPlan.objects.get_or_create(
                title=data["title"],
                defaults={k: data[k] for k in ("icon", "summary", "highlights", "body")} | {"order": order},
            )
            if created:
                for i, (q, a) in enumerate(data["faqs"]):
                    FAQ.objects.create(plan=plan, question=q, answer=a, order=i)
            (self.ok if created else self.skip)(f"طرح «{plan.title}»" + ("" if created else " از قبل وجود دارد"))
        for i, (q, a) in enumerate(GENERAL_FAQS):
            FAQ.objects.get_or_create(question=q, defaults={"answer": a, "order": i})

    def bot(self):
        for order, (title, keywords, answer, url, label) in enumerate(BOT_ANSWERS):
            _, created = BotAnswer.objects.get_or_create(
                title=title, defaults={"keywords": keywords, "answer": answer, "link_url": url, "link_label": label, "order": order},
            )
            (self.ok if created else self.skip)(f"پاسخ چت‌بات «{title}»" + ("" if created else " از قبل وجود دارد"))
